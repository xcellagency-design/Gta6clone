import { el } from './dom';

export interface MenuActions {
  newGame(): void;
  continueGame(): void;
  hasSave(): boolean;
  resume(): void;
  quitToMenu(): void;
  settings: { quality: string; sensitivity: number; volume: number; invertY: boolean };
  applySettings(): void;
  /** Extra pause-menu entries added by later systems (map, save, character…). */
  pauseItems: { label: string; hint?: string; run(): void }[];
}

const CONTROLS: [string, string][] = [
  ['W A S D', 'Move / steer'], ['Mouse', 'Look'], ['Shift', 'Sprint'], ['Space', 'Jump / handbrake'], ['C', 'Crouch'],
  ['F', 'Enter or leave a vehicle'], ['E', 'Interact'], ['M', 'Map'], ['Esc', 'Pause'], ['F3', 'Streaming overlay'], ['`', 'Developer console'],
];

/** Main menu, pause menu, settings and controls. */
export class Menu {
  private layer = el('div');
  private fade = el('div.fade');
  screen: 'none' | 'main' | 'pause' | 'settings' | 'controls' | 'custom' = 'none';
  private back: 'main' | 'pause' = 'main';

  constructor(private parent: HTMLElement, private a: MenuActions) {
    parent.append(this.layer, this.fade);
  }

  get open(): boolean {
    return this.screen !== 'none';
  }

  private show(node: HTMLElement | null, name: Menu['screen']): void {
    this.layer.replaceChildren();
    this.screen = name;
    if (node) { this.layer.append(node); (node.querySelector('button:not(:disabled)') as HTMLElement | null)?.focus(); }
  }

  close(): void {
    this.show(null, 'none');
  }

  /** Show an arbitrary panel (map, save slots, shop…) as a centred screen. */
  custom(panel: HTMLElement): void {
    this.show(el('div.screen.center', panel), 'custom');
  }

  async fadeThrough(work: () => Promise<void> | void): Promise<void> {
    this.fade.classList.add('on');
    await new Promise((r) => setTimeout(r, 380));
    await work();
    this.fade.classList.remove('on');
  }

  main(): void {
    this.back = 'main';
    const cont = el('button', { onclick: () => this.a.continueGame(), disabled: !this.a.hasSave() }, 'Continue', el('small', this.a.hasSave() ? 'Load the most recent save' : 'No save found'));
    this.show(
      el('div.screen',
        el('div.menu',
          el('h1.title', 'UNDERTOW'),
          el('div.subtitle', 'Port Meridian'),
          el('button', { onclick: () => this.a.newGame() }, 'New Game', el('small', 'Start at Navarro Salvage')),
          cont,
          el('button', { onclick: () => this.settings() }, 'Settings'),
          el('button', { onclick: () => this.controls() }, 'Controls'),
          el('div.fine', 'An original open-world crime game. All art, models and audio are procedural placeholders generated by the game’s own code.'),
        )),
      'main');
  }

  pause(): void {
    this.back = 'pause';
    this.show(
      el('div.screen',
        el('div.menu',
          el('h1.title', 'PAUSED'),
          el('div.subtitle', 'Port Meridian'),
          el('button', { onclick: () => this.a.resume() }, 'Resume'),
          ...this.a.pauseItems.map((i) => el('button', { onclick: () => i.run() }, i.label, i.hint ? el('small', i.hint) : null)),
          el('button', { onclick: () => this.settings() }, 'Settings'),
          el('button', { onclick: () => this.controls() }, 'Controls'),
          el('button', { onclick: () => this.a.quitToMenu() }, 'Quit to Main Menu'),
        )),
      'pause');
  }

  private backBtn(): HTMLElement {
    return el('button', { onclick: () => (this.back === 'main' ? this.main() : this.pause()) }, '← Back');
  }

  settings(): void {
    const s = this.a.settings;
    const quality = el('select', { onchange: () => { s.quality = quality.value; this.a.applySettings(); } },
      ...['low', 'medium', 'high'].map((q) => el('option', { value: q, selected: q === s.quality }, q)));
    const sens = el('input', { type: 'range', min: '0.3', max: '3', step: '0.1', value: String(s.sensitivity), oninput: () => { s.sensitivity = Number(sens.value); this.a.applySettings(); } });
    const vol = el('input', { type: 'range', min: '0', max: '1', step: '0.05', value: String(s.volume), oninput: () => { s.volume = Number(vol.value); this.a.applySettings(); } });
    const inv = el('input', { type: 'checkbox', checked: s.invertY, onchange: () => { s.invertY = inv.checked; this.a.applySettings(); } });
    this.show(
      el('div.screen.center',
        el('div.panel',
          el('h2', 'Settings'),
          el('div.row', 'Graphics quality', quality),
          el('div.fine', 'Quality changes draw distance, shadows, population and resolution. It applies after a reload of the world.'),
          el('div.row', 'Mouse sensitivity', sens),
          el('div.row', 'Invert vertical look', inv),
          el('div.row', 'Master volume', vol),
          el('h3', ''), this.backBtn(),
        )),
      'settings');
  }

  controls(): void {
    const keys = el('div.keys');
    for (const [k, d] of CONTROLS) keys.append(el('b', k), el('span', d));
    this.show(el('div.screen.center', el('div.panel', el('h2', 'Controls'), keys, el('h3', ''), this.backBtn(), el('div.fine', 'A gamepad also works: left stick to move, right stick to look, triggers to accelerate and brake.'))), 'controls');
  }
}
